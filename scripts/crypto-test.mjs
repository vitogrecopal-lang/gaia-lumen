import assert from 'node:assert/strict';
import { newWallet, trade, valuation, importWalletCsv } from '../crypto-model.js';
import { validatePrices } from '../crypto-prices.mjs';
import { createAsmodeusPulse, validAsmodeusPulse } from '../asmodeus-pulse.js';
const now=Date.now();
const market=validatePrices(Object.fromEntries([['bitcoin',70000],['solana',100],['crypto-com-chain',0.05]].map(([id,eur])=>[id,{eur,last_updated_at:now/1000}])),now);
let w=newWallet(4);
w=trade(w,market,{symbol:'SOL',side:'buy',amount:2,feePercent:0},now);
assert.equal(w.cash,2);assert.equal(w.holdings.SOL,0.02);
assert.equal(valuation(w,market,{SOL:20}),4.4);
const sell=trade(w,market,{symbol:'SOL',side:'sell',amount:0.02,feePercent:1},now);
assert.equal(sell.cash,3.98);assert.equal(sell.holdings.SOL,0);
assert.throws(()=>trade(w,market,{symbol:'SOL',side:'buy',amount:3,feePercent:0},now),/insufficienti/);
assert.throws(()=>trade(w,market,{symbol:'SOL',side:'sell',amount:0.03,feePercent:0},now),/insufficiente/);
assert.throws(()=>trade(w,{...market,stale:true},{symbol:'SOL',side:'buy',amount:1,feePercent:0},now),/Aggiorna/);
assert.throws(()=>trade(w,market,{symbol:'SOL',side:'buy',amount:1,feePercent:0},now+600001),/Aggiorna/);
assert.throws(()=>newWallet(''),/non valido/);
assert.throws(()=>validatePrices({}),/incompleti/);
assert.equal(valuation(w,{prices:{}}),null);
console.log('Crypto: acquisto, vendita, costi, scenari, limiti e dati scaduti verificati.');
const header='data;operazione_virtuale;moneta;quantita;prezzo_eur;costo_eur';
const csv='\uFEFF'+header+'\r\n2026-10-31T06:03:54.813Z;buy;SOL;0.046212322515798834;85.7;0.039603960396039604\r\n';
const imported=importWalletCsv(csv,4);
assert.equal(imported.cash,0); assert.equal(imported.holdings.SOL,0.046212322515798834); assert.equal(imported.trades.length,1);
assert.throws(()=>importWalletCsv(csv,1),/insufficiente/);
assert.throws(()=>importWalletCsv(header+'\n2026-10-30T00:00:00Z;sell;SOL;1;100;0'),/incompleto/);
assert.throws(()=>importWalletCsv(csv.replace(';buy;',';<script>;')),/non valida/);
assert.throws(()=>importWalletCsv(csv.replace(';85.7;',';NaN;')),/non valido/);
const replay=importWalletCsv(header+'\n2026-10-31T06:03:55Z;sell;SOL;0.01;100;0\n2026-10-31T06:03:54Z;buy;SOL;0.02;100;0',4);
assert.equal(replay.cash,3); assert.equal(replay.holdings.SOL,0.01);
console.log('CSV: importazione, capitale, replay e righe non valide verificati.');
const originalWallet=JSON.stringify(imported);
const shocks=Array.from({length:14},(_,i)=>createAsmodeusPulse(i+1));
assert.ok(shocks.every(p=>validAsmodeusPulse(p)));
assert.deepEqual(shocks.slice(0,7).map(p=>p.solChange),[100,100,100,100,100,100,100]);
assert.deepEqual(shocks.slice(0,7).map(p=>p.solChange),shocks.slice(7).map(p=>p.solChange));
assert.ok(!validAsmodeusPulse({...shocks[0],solChange:1000000}));
assert.ok(!validAsmodeusPulse(shocks[0],shocks[0].at+30001));
assert.throws(()=>createAsmodeusPulse(-1));
for(const pulse of shocks) valuation(imported,market,{SOL:pulse.solChange});
assert.equal(JSON.stringify(imported),originalWallet);
assert.equal(valuation(w,market,{SOL:-100}),w.cash);
assert.equal(valuation(w,market,{SOL:100}),w.cash+2*w.holdings.SOL*market.prices.SOL.eur);
console.log('Asmodeus: scenario fisso +100%, messaggi scaduti e invariabilita del portafoglio verificati.');
