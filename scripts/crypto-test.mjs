import assert from 'node:assert/strict';
import { newWallet, trade, valuation } from '../crypto-model.js';
import { validatePrices } from '../crypto-prices.mjs';
const now=Date.now();
const market=validatePrices(Object.fromEntries([['bitcoin',70000],['solana',100],['crypto-com-chain',0.05]].map(([id,eur])=>[id,{eur,last_updated_at:now/1000}])),now);
let w=newWallet(4);
w=trade(w,market,{symbol:'SOL',side:'buy',amount:2,feePercent:0},now);
assert.equal(w.cash,2);assert.equal(w.holdings.SOL,0.02);
assert.equal(valuation(w,market,{SOL:20}),4.4);
const sell=trade(w,market,{symbol:'SOL',side:'sell',amount:0.02,feePercent:1},now);
assert.equal(sell.cash,3.98);assert.equal(sell.holdings.SOL,0);
assert.throws(()=>trade(w,market,{symbol:'SOL',side:'buy',amount:3,feePercent:0},now),/insufficienti/);
assert.throws(()=>trade(w,market,{symbol:'SOL',side:'sell',amount:0.03,feePercent:0},now),/insufficiente/);
assert.throws(()=>trade(w,{...market,stale:true},{symbol:'SOL',side:'buy',amount:1,feePercent:0},now),/Aggiorna/);
assert.throws(()=>trade(w,market,{symbol:'SOL',side:'buy',amount:1,feePercent:0},now+600001),/Aggiorna/);
assert.throws(()=>newWallet(''),/non valido/);
assert.throws(()=>validatePrices({}),/incompleti/);
assert.equal(valuation(w,{prices:{}}),null);
console.log('Crypto: acquisto, vendita, costi, scenari, limiti e dati scaduti verificati.');
